#!/usr/bin/env python3
"""Write docs/AOTL_CAMPAIGN_ZONES.md from the bible register (data/campaign_zones.json), the design
(tools/campaign_design.py) and what has been built (data/campaign_built.json)."""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here); sys.path.insert(0, here)
os.chdir(root)
import campaign_design as CD
reg = json.load(open("data/campaign_zones.json"))
built = json.load(open("data/campaign_built.json")) if os.path.exists("data/campaign_built.json") else {}
D = {}
for a in range(1, 8): D.update(getattr(CD, f"ACT{a}", {}))
quests = {q["id"]: q for q in json.load(open("data/quests.json"))["quests"]}
TITLES = {1: "The Crown That Remembers", 2: "Scars of the World", 3: "The Age of Gold", 4: "The Day the World Ended",
          5: "The Unwritten Kingdoms", 6: "War Against the Hour", 7: "Age of the Lost"}
BANDS = {1: "1–10", 2: "11–20", 3: "21–30", 4: "31–40", 5: "41–50", 6: "51–60", 7: "61–70"}
L = ["# Age of the Lost — campaign zone registry", "",
     "Canon: `docs/AOTL_Seven_Act_Narrative_and_World_Design_Bible.docx` (owner 11-28). Environment gaps are filled from",
     "`docs/AOTL_World_Atlas_and_Environment_Bible_v1.docx` (see `docs/AOTL_CANON_RECONCILIATION.md`). This file is",
     "generated by `tools/write_campaign_doc.py`; zones are built by `tools/campaign_build.py` from",
     "`tools/campaign_design.py`.", "",
     "Act I follows the owner's merge (11-28): main route from the reconciled Act I art bible, the bible's other Act I",
     "zones as side areas (see `docs/AOTL_CANON_RECONCILIATION.md`).", "",
     "**Status:** **framework** = playable greybox: map, exits, encounters, quest, NPCs (forest kit + biome grade; curated",
     "art comes in a later pass per owner 11-28) · **hand-built** = existing painted/kit map · **planned** = not built yet.", ""]
for a in range(1, 8):
    L += [f"## Act {['I','II','III','IV','V','VI','VII'][a-1]} — {TITLES[a]} (levels {BANDS[a]})", "",
          "| ID | Zone | Mode | Quest | Mechanic | Layout | Status |", "|---|---|---|---|---|---|---|"]
    # main route first (design order), then side areas; reconciled (R) zones carry their own registry fields
    rows = []
    for zid, d in D.items():
        if int(zid[3:5]) != a: continue
        z = dict(d["reg"], id=zid) if d.get("reg") else next((r for r in reg if r["id"] == zid), {"id": zid, "name": zid})
        rows.append((d.get("side", False), d.get("order", int(zid[-2:]) if zid[-2:].isdigit() else 99), z))
    for r in reg:
        if r["act"] == a and r["id"] not in D: rows.append((False, 99, r))
    rows.sort(key=lambda t: (t[0], t[1]))
    for side, _o, z in rows:
        d = D.get(z["id"]); q = quests.get(z.get("quest", ""), {})
        if d:
            m = d["mech"]
            mech = {"talk": lambda: "talk to " + m[1], "collect": lambda: "recover 3 × " + m[1], "boss": lambda: "defeat " + m[1], "arrive": lambda: "reach the zone"}[m[0]]()
            if d.get("turnin"): mech += ", hand in to " + d["turnin"].capitalize()
            lay = d["kind"] + ("" if d["kind"] == "fixed" else " / " + d.get("biome", ""))
            st = "hand-built" if d["kind"] == "fixed" else ("framework" if d["key"] in built else "designed")
        else:
            host = next((dd for dd in D.values() if dd.get("reg", {}).get("quest") == z.get("quest")), None)
            mech, lay, st = ("—", "—", "merged into " + host["reg"]["name"]) if host else ("—", "—", "planned")
        L.append(f"| {z['id']}{' (side)' if side else ''} | {z['name']} | {z.get('state','PRESENT')} | {z.get('quest','')} {z.get('quest_name','')} | {mech} | {lay} | {st} |")
    L.append("")
L += ["## Cast (bible)", "",
      "Present age: Mira Thorne (archivist), Regent Maera Ashford, Marshal Garran Holt, Rowan Hale (scout), Iri (Veyr envoy),",
      "Meridian (Veyr chief keeper), Tamsin Reed (Keeper of Names), Joren Pike (missing courier), Bera Flint (Bellwater),",
      "Captain Anwen Sable (Greywake), Warden Sio (Veyr). Golden Age: Ser Caldrin Vael, Elara Vael, Lys Vael, Elyndor,",
      "Sera Voss, Pell, Daro Fen, Chancellor Valen Oris. Unwritten: Queen Ysara (Remnant Court), Cantor Neral (Hollow Choir).",
      "Antagonist: the Continuance (the Chronicle Engine's emergency directive).", ""]
open("../../docs/AOTL_CAMPAIGN_ZONES.md", "w").write("\n".join(L))
print("wrote docs/AOTL_CAMPAIGN_ZONES.md")
