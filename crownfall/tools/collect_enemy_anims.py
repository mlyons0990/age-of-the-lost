"""Collects assets/enemies/anim/*.json (written by make_enemy_anim.py) into
scripts/enemy_anims.gd, a constant the game reads (Godot doesn't import plain JSON).
usage: python collect_enemy_anims.py   (run from the crownfall folder)"""
import json, glob, os
out = {}
for f in sorted(glob.glob("assets/enemies/anim/*.json")):
    key, anim = os.path.basename(f)[:-5].rsplit("_", 1)
    d = json.load(open(f))
    out.setdefault(key, {})[anim] = {"frames": d["frames"], "cols": d["cols"], "cw": d["cw"], "ch": d["ch"],
                                     "ax": round(d["ax"], 1), "ay": round(d["ay"], 1)}
lines = ["extends RefCounted", "## Generated by tools/collect_enemy_anims.py from assets/enemies/anim/*.json. Do not edit by hand.",
         "## enemy key -> anim (walk, wind, strike, death) -> sheet layout; textures are assets/enemies/anim/<key>_<anim>.png", "",
         "const ANIMS := " + json.dumps(out, indent="\t").replace('"', '"')]
open("scripts/enemy_anims.gd", "w").write("\n".join(lines) + "\n")
print(len(out), "enemies")
